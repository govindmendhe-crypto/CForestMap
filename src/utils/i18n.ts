export function getTranslation(key: string, lang: string): string {
  const dict = I18N_DICTIONARIES[lang];
  if (dict && dict[key] !== undefined) return dict[key];
  const mr = I18N_DICTIONARIES.mr;
  if (mr && mr[key] !== undefined) return mr[key];
  const hi = I18N_DICTIONARIES.hi;
  if (hi && hi[key] !== undefined) return hi[key];
  const en = I18N_DICTIONARIES.en;
  if (en && en[key] !== undefined) return en[key];
  return key;
}
