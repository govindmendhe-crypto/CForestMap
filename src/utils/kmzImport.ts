import JSZip from 'jszip';
import {
  BoundaryPillar,
  FeaturePreset,
  GeoRef,
  LatLonPoint,
  NonWorkingAreaItem,
  Point2D
} from '../types/mapTypes';
import { SavedCoupeProject, parseProjectJsonBackup } from './fieldTools';
import { calcAreaHa, formatToDMY, getMetersPerDegree } from './geoUtils';

export interface ImportedKmzResult {
  project: SavedCoupeProject;
  mode: 'full_project' | 'kml_reconstructed' | 'json_backup';
}

function parseKmlCoordString(text: string): LatLonPoint[] {
  const pts: LatLonPoint[] = [];
  const tokens = text.trim().split(/\s+/);
  for (const tok of tokens) {
    const parts = tok.split(',');
    if (parts.length >= 2) {
      const lon = parseFloat(parts[0]);
      const lat = parseFloat(parts[1]);
      if (Number.isFinite(lat) && Number.isFinite(lon)) {
        pts.push({ lat, lon });
      }
    }
  }
  return pts;
}

function getDirectTagText(el: Element, tagName: string): string {
  const child = el.getElementsByTagName(tagName)[0];
  return child?.textContent?.trim() || '';
}

function getFolderNameForElement(el: Element): string {
  let cur: Element | null = el.parentElement;
  while (cur) {
    if (cur.tagName.toLowerCase() === 'folder') {
      for (let i = 0; i < cur.children.length; i++) {
        if (cur.children[i].tagName.toLowerCase() === 'name') {
          return cur.children[i].textContent?.trim() || '';
        }
      }
    }
    cur = cur.parentElement;
  }
  return '';
}

/**
 * Fast check: if a .kmz file was generated by this app with an embedded lossless
 * `files/forest_project.json`, extract and return the complete SavedCoupeProject.
 */
export async function extractEmbeddedProjectFromKmz(file: File): Promise<SavedCoupeProject | null> {
  try {
    const zip = await JSZip.loadAsync(file);
    const jsonEntry =
      zip.file('files/forest_project.json') ||
      zip.file('forest_project.json') ||
      Object.values(zip.files).find((f) => f.name.toLowerCase().endsWith('forest_project.json'));
    if (!jsonEntry) return null;

    const rawText = await jsonEntry.async('text');
    const parsed = parseProjectJsonBackup(rawText);
    if (!parsed) return null;

    return {
      ...parsed,
      savedAt: Date.now(),
      source: 'kmz_import',
      kmzFileName: file.name
    };
  } catch {
    return null;
  }
}

/**
 * Reconstructs a SavedCoupeProject from any KML text (including older app-generated KMZs
 * exported before embedded project JSON, or standard field KMLs).
 */
function reconstructProjectFromKmlText(kmlText: string, fileName: string): SavedCoupeProject | null {
  const parser = new DOMParser();
  const xml = parser.parseFromString(kmlText, 'text/xml');
  if (xml.getElementsByTagName('parsererror').length > 0) {
    return null;
  }

  const docName =
    xml.getElementsByTagName('Document')[0]?.getElementsByTagName('name')[0]?.textContent?.trim() ||
    fileName.replace(/\.(kmz|kml)$/i, '');

  const placemarks = Array.from(xml.getElementsByTagName('Placemark'));

  interface RawPolyCandidate {
    name: string;
    folderName: string;
    styleUrl: string;
    coords: LatLonPoint[];
    approxArea: number;
  }

  const polyCandidates: RawPolyCandidate[] = [];
  const rawPillars: { name: string; lat: number; lon: number }[] = [];
  const rawLandmarks: { name: string; lat: number; lon: number }[] = [];

  for (const pm of placemarks) {
    const name = getDirectTagText(pm, 'name');
    const styleUrl = getDirectTagText(pm, 'styleUrl').toLowerCase();
    const folderName = getFolderNameForElement(pm);
    const folderLower = folderName.toLowerCase();
    const nameLower = name.toLowerCase();

    // Skip grid block polygons (Folder 7) so they aren't mistaken for boundary or non-working polygons
    const isGridCellFolder =
      folderLower.includes('grid polygons') ||
      folderLower.includes('ग्रीड ब्लॉक्स') ||
      styleUrl.includes('gridcell');

    const polygons = Array.from(pm.getElementsByTagName('Polygon'));
    if (polygons.length > 0 && !isGridCellFolder) {
      for (const poly of polygons) {
        const coordEl = poly.getElementsByTagName('coordinates')[0];
        if (!coordEl?.textContent) continue;
        const coords = parseKmlCoordString(coordEl.textContent);
        if (coords.length < 3) continue;
        // Rough bounding box area for sorting/selection
        let minLat = 90,
          maxLat = -90,
          minLon = 180,
          maxLon = -180;
        coords.forEach((c) => {
          if (c.lat < minLat) minLat = c.lat;
          if (c.lat > maxLat) maxLat = c.lat;
          if (c.lon < minLon) minLon = c.lon;
          if (c.lon > maxLon) maxLon = c.lon;
        });
        const approxArea = (maxLat - minLat) * (maxLon - minLon);
        polyCandidates.push({ name, folderName, styleUrl, coords, approxArea });
      }
      continue;
    }

    // Check Point placemarks (Boundary Pillars vs Landmarks)
    const ptEl = pm.getElementsByTagName('Point')[0];
    if (ptEl) {
      const coordEl = ptEl.getElementsByTagName('coordinates')[0];
      if (!coordEl?.textContent) continue;
      const pts = parseKmlCoordString(coordEl.textContent);
      if (pts.length === 0) continue;
      const { lat, lon } = pts[0];

      const isPillar =
        folderLower.includes('pillar') ||
        folderLower.includes('सीमा खांब') ||
        styleUrl.includes('pillar') ||
        /^bp[-\s]?\d+/i.test(name);

      const isLandmark =
        folderLower.includes('landmark') ||
        folderLower.includes('भूप्रदेश खुणा') ||
        styleUrl.includes('landmark');

      if (isPillar) {
        rawPillars.push({ name: name || `BP-${rawPillars.length + 1}`, lat, lon });
      } else if (isLandmark) {
        rawLandmarks.push({ name: name || `Landmark ${rawLandmarks.length + 1}`, lat, lon });
      }
    }
  }

  if (polyCandidates.length === 0) return null;

  // Pick Boundary polygon: prefer Folder 1 / boundaryStyle / "boundary", else largest polygon
  let boundaryIdx = polyCandidates.findIndex(
    (c) =>
      c.styleUrl.includes('boundarystyle') ||
      c.folderName.toLowerCase().includes('boundary') ||
      c.folderName.includes('कूप क्षेत्र सीमा')
  );
  if (boundaryIdx === -1) {
    boundaryIdx = 0;
    let bestArea = -1;
    polyCandidates.forEach((c, idx) => {
      if (c.approxArea > bestArea) {
        bestArea = c.approxArea;
        boundaryIdx = idx;
      }
    });
  }

  const boundaryCand = polyCandidates[boundaryIdx];
  const boundaryCoords = boundaryCand.coords;

  let minLat = 90,
    maxLat = -90,
    minLon = 180,
    maxLon = -180;
  boundaryCoords.forEach((c) => {
    if (c.lat < minLat) minLat = c.lat;
    if (c.lat > maxLat) maxLat = c.lat;
    if (c.lon < minLon) minLon = c.lon;
    if (c.lon > maxLon) maxLon = c.lon;
  });

  const cLat = (minLat + maxLat) / 2;
  const cLon = (minLon + maxLon) / 2;
  const { latM, lonM } = getMetersPerDegree(cLat);

  const toLocal = (c: LatLonPoint): Point2D => ({
    x: (c.lon - cLon) * lonM,
    y: (c.lat - cLat) * latM
  });

  const rawWorkingPoints: Point2D[] = boundaryCoords.map(toLocal);
  const geoRef: GeoRef = {
    hasGeo: true,
    centerLat: cLat,
    centerLon: cLon,
    northLat: maxLat,
    southLat: minLat,
    eastLon: maxLon,
    westLon: minLon
  };

  // Reconstruct Non-Workable items (other polygons, e.g. Roads, Nalas, Patches)
  const nonWorkingFiles: NonWorkingAreaItem[] = [];
  polyCandidates.forEach((cand, idx) => {
    if (idx === boundaryIdx) return;
    const pts = cand.coords.map(toLocal);
    if (pts.length < 3) return;
    const lowerName = cand.name.toLowerCase();
    const isRoad =
      cand.styleUrl.includes('road') || lowerName.includes('road') || cand.name.includes('रस्ता');
    const isNala =
      cand.styleUrl.includes('nala') || lowerName.includes('nala') || cand.name.includes('नाला');
    const areaHa = Number(calcAreaHa(pts).toFixed(2));
    nonWorkingFiles.push({
      id: `nw_kmz_${Date.now()}_${idx}`,
      fileName: cand.name || `Non-Workable ${idx + 1}`,
      pts,
      areaHa,
      category: isRoad ? 'road' : isNala ? 'nala' : 'patch'
    });
  });

  // Reconstruct Boundary Pillars
  const boundaryPillars: BoundaryPillar[] = rawPillars.map((p, idx) => {
    const local = toLocal({ lat: p.lat, lon: p.lon });
    const shortLabel = p.name.split(/[—(-]/)[0]?.trim() || `BP-${idx + 1}`;
    return {
      id: `bp_kmz_${Date.now()}_${idx}`,
      label: shortLabel,
      mx: local.x,
      my: local.y,
      lat: p.lat,
      lon: p.lon,
      timestamp: Date.now()
    };
  });

  // Reconstruct Landmarks into a single custom preset if any were present
  const features: FeaturePreset[] = [];
  if (rawLandmarks.length > 0) {
    features.push({
      id: 'imported_kmz_landmarks',
      label: 'Imported Landmarks',
      symbol: '📍',
      color: '#0f766e',
      enabled: true,
      custom: true,
      markers: rawLandmarks.map((lm) => {
        const local = toLocal({ lat: lm.lat, lon: lm.lon });
        return {
          mx: local.x,
          my: local.y,
          lat: lm.lat,
          lon: lm.lon,
          label: lm.name
        };
      })
    });
  }

  const grossHa = calcAreaHa(rawWorkingPoints);
  const nwHa = nonWorkingFiles.reduce((s, it) => s + it.areaHa, 0);
  const netHa = Math.max(0, grossHa - nwHa);

  const cleanName = docName.replace(/_GoogleEarth$/i, '').trim() || fileName.replace(/\.(kmz|kml)$/i, '');

  return {
    id: `coupe_kmz_${Date.now()}`,
    name: cleanName,
    savedAt: Date.now(),
    schemaVersion: 1,
    source: 'kmz_import',
    kmzFileName: fileName,
    rawWorkingPoints,
    nonWorkingFiles,
    isNonWorkingNil: nonWorkingFiles.length === 0,
    geoRef,
    workingFileName: fileName,
    nonWorkingFileName: nonWorkingFiles.map((f) => f.fileName).join(', '),
    boundaryPillars,
    features,
    scaleId: '1_5000',
    customScaleCm: 2,
    customScaleM: 100,
    gridWidthM: 100,
    gridHeightM: 100,
    orientation: 'landscape',
    baselineOption: 'horizontal',
    manualBaselineOffset: { x: 0, y: 0 },
    showSectionLines: false,
    sectionLineOffset: 0,
    rotationDeg: 0,
    legendPos: 'top-right',
    legendLayout: 'box',
    legendSize: 'compact',
    legendOffset: { x: 0, y: 0 },
    displayOptions: {
      showBoundary: true,
      showNonWorking: true,
      showLandmarks: true,
      showBaseline: true,
      showBaselineMeas: true,
      showSectionLines: false,
      showEdgeGps: true,
      showGridNaming: true,
      showGridNumbers: true,
      showGridLines: true
    },
    treatmentTitle: cleanName,
    village: '',
    landIdentifierType: 'compartment',
    landIdentifierValue: cleanName,
    division: '',
    subDivision: '',
    range: '',
    round: '',
    beat: '',
    compartmentNo: cleanName,
    mapDate: formatToDMY(),
    treatmentType: 'nirmulan',
    customTreatmentType: '',
    plantSpacingM: 2,
    targetTotalPlants: 0,
    vanrakshak: '',
    vanpal: '',
    rfo: '',
    totalAreaHa: grossHa.toFixed(2),
    treatmentAreaHa: netHa.toFixed(2)
  };
}

/**
 * Unified importer for the Saved KMZ & Field Folder:
 * Supports app-generated `.kmz` (lossless full project restore), legacy/external `.kmz`/`.kml`,
 * and `.json` project backups.
 */
export async function parseAppKmzForInspection(file: File): Promise<ImportedKmzResult | null> {
  const lower = file.name.toLowerCase();

  if (lower.endsWith('.json')) {
    const text = await file.text();
    const parsed = parseProjectJsonBackup(text);
    if (!parsed) return null;
    return {
      project: { ...parsed, source: 'json_import' },
      mode: 'json_backup'
    };
  }

  if (lower.endsWith('.kmz')) {
    // 1. Try lossless embedded project JSON first
    const embedded = await extractEmbeddedProjectFromKmz(file);
    if (embedded) {
      return { project: embedded, mode: 'full_project' };
    }

    // 2. Fallback: reconstruct from doc.kml inside the KMZ archive
    const zip = await JSZip.loadAsync(file);
    const kmlEntry =
      zip.file('doc.kml') ||
      Object.values(zip.files).find((f) => !f.dir && f.name.toLowerCase().endsWith('.kml'));
    if (!kmlEntry) return null;
    const kmlText = await kmlEntry.async('text');
    const reconstructed = reconstructProjectFromKmlText(kmlText, file.name);
    if (!reconstructed) return null;
    return { project: reconstructed, mode: 'kml_reconstructed' };
  }

  if (lower.endsWith('.kml')) {
    const kmlText = await file.text();
    const reconstructed = reconstructProjectFromKmlText(kmlText, file.name);
    if (!reconstructed) return null;
    return { project: reconstructed, mode: 'kml_reconstructed' };
  }

  return null;
}
